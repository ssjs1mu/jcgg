#!/usr/bin/env python3
"""Build js/versions.js — version number, last-updated time and change history for every module — from git history.
Usage before a commit:  python3 tools/release.py "What changed (one line)"
It counts the staged change as the newest release of every module whose files are staged, then stages js/versions.js."""
import subprocess, sys, json, datetime, re, os
os.chdir(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
IST = datetime.timezone(datetime.timedelta(hours=5, minutes=30))
FILES = {
  "platform": ["index.html", "css/app.css", "js/core.js", "js/files.js", "js/firebase-config.js", "js/entries.js", "firestore.rules", "sw.js", "manifest.webmanifest"],
  "home": ["js/mod-home.js", "js/panchang.js", "js/home-plus.js", "js/home-tabs.js", "js/astro.js"], "jdash": ["js/mod-jdash.js"], "promo": ["js/promo.js"],
  "inventory": ["js/mod-inventory.js", "js/bills.js", "js/picpick.js"],
  "kitchen": ["js/mod-kitchen.js", "js/kitchen-plus.js", "js/recipe-lib.js", "js/picpick.js"],
  "kot": ["js/mod-staffkot.js", "js/mod-kot.js"],
  "staff": ["js/mod-staff.js", "js/escrow.js", "js/mod-people.js", "js/mod-rules.js", "js/access.js"],
  "care": ["js/care.js", "docs/customer-care.md"],
  "directory": ["js/mod-directory.js", "js/mod-clients.js"],
  "accounts": ["js/mod-accounts.js", "js/bankmatch.js", "js/expcat.js", "js/connections.js", "js/movepick.js", "js/bankpdf.js", "js/loans.js"],
  "invest": ["js/mod-invest.js"], "dues": ["js/dues.js"], "assets": ["js/mod-assets.js", "js/upkeep.js"], "insurance": ["js/mod-assets.js"],
  "settings": ["js/mod-settings.js", "js/access.js"], "import": ["js/mod-import.js", "js/bankpdf.js"],
  "manual": ["js/manual.js"], "sales": ["js/mod-sales.js"],
}
def git(*a): return subprocess.run(["git", *a], capture_output=True, text=True, check=True).stdout
log = git("log", "--reverse", "--format=@@%H|%at|%s", "--name-only")
commits = []
for block in log.split("@@")[1:]:
    head, *files = block.strip().split("\n")
    h, at, msg = head.split("|", 2)
    commits.append({"at": int(at), "msg": msg, "files": [f for f in files if f]})
msg = " ".join(sys.argv[1:]).strip()
staged = [f for f in git("diff", "--cached", "--name-only").split("\n") if f and f != "js/versions.js"]
if msg and staged:
    commits.append({"at": int(datetime.datetime.now().timestamp()), "msg": msg, "files": staged})
out = {}
for mod, fl in FILES.items():
    hist = [c for c in commits if any(f in fl for f in c["files"])]
    if not hist: continue
    rel = []
    for i, c in enumerate(hist, 1):
        t = datetime.datetime.fromtimestamp(c["at"], IST)
        rel.append({"v": f"1.{i}", "at": t.strftime("%Y-%m-%d %H:%M"), "msg": c["msg"]})
    rel.reverse()
    out[mod] = {"v": rel[0]["v"], "at": rel[0]["at"], "hist": rel[:60]}
allc = commits
t = datetime.datetime.fromtimestamp(allc[-1]["at"], IST)
app = {"v": f"1.{len(allc)}", "at": t.strftime("%Y-%m-%d %H:%M")}
js = "/* Generated by tools/release.py from the git history — do not edit by hand. */\nwindow.JCGG_VERSIONS=" + json.dumps({"app": app, "mods": out}, ensure_ascii=False, separators=(",", ":")) + ";\n"
open("js/versions.js", "w").write(js)
subprocess.run(["git", "add", "js/versions.js"])
print("app", app, "modules", {k: v["v"] for k, v in out.items()})
